export function t(id, parameters = {}) {
  const template = messages[id];
  if (template == null) throw new Error(`missing_message:${id}`);
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (_, key) => String(parameters[key] ?? `{${key}}`));
}

export function presentProblem(result = {}) {
  const errorCode = String(result.errorCode || "internal_error");
  const key = `error.${errorCode}`;
  let error;
  try {
    error = t(key, result.parameters || {});
  } catch {
    error = t("error.internal_error");
  }
  return { ...result, errorCode, error };
}
